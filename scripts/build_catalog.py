"""Build the offline browser data file. Maintainer tool; no dependencies."""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def render_catalog():
    data = json.loads((ROOT / 'catalog/songs.json').read_text(encoding='utf-8'))
    payload = json.dumps(data, ensure_ascii=False, indent=2).replace('</', '<\\/')
    return '// Generated by scripts/build_catalog.py; edit catalog/songs.json.\nwindow.HARMONICA_CATALOG = ' + payload + ';\n'


if __name__ == '__main__':
    (ROOT / 'assets/catalog.js').write_text(render_catalog(), encoding='utf-8', newline='\n')
    print('Updated assets/catalog.js')
